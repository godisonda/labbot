def render_prompt(template: str, values: Mapping[str, Any]) -> str:
    """Подставляет <<ключи>>. Неизвестные подстановки остаются как есть."""
    result = template or ""
    for key, value in values.items():
        result = result.replace(f"<<{key}>>", str(value))
    return result


def build_system_context(override: Optional[str] = None) -> str:
    return (override or DEFAULT_SYSTEM_PROMPT).strip()


def prompt_defaults() -> Dict[str, str]:
    return dict(DEFAULT_PROMPTS)


def merge_prompts(custom: Optional[Mapping[str, Any]]) -> Dict[str, str]:
    merged = dict(DEFAULT_PROMPTS)
    if custom:
        for key, value in custom.items():
            if key in merged and isinstance(value, str) and value.strip():
                merged[key] = value
    return merged
